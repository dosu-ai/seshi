import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const PACK_PATH = "packages/ts/redact/packs/builtin.toml";
export const GENERATED_PATH = "packages/ts/redact/src/generated/builtin-pack.ts";

const REPO = join(import.meta.dirname, "..");

function format(text: string): string {
  const result = Bun.spawnSync(["bunx", "biome", "format", `--stdin-file-path=${GENERATED_PATH}`], {
    cwd: REPO,
    stdin: new TextEncoder().encode(text),
    stdout: "pipe",
    stderr: "pipe",
  });
  if (result.exitCode !== 0) {
    throw new Error(`biome could not format ${GENERATED_PATH}: ${result.stderr.toString()}`);
  }
  return result.stdout.toString();
}

export function generated(text: string): string {
  return format(
    [
      `// Generated by scripts/builtin-pack.ts from ${PACK_PATH}. Do not edit: edit the TOML and`,
      "// run `bun run packs`.",
      "",
      "/** The built-in rule pack's TOML, exactly as the file holds it. */",
      `export const BUILTIN_PACK_TOML: string = ${JSON.stringify(text)};`,
      "",
    ].join("\n"),
  );
}

export function isStale(root: string): boolean {
  const want = generated(readFileSync(join(root, PACK_PATH), "utf8"));
  const path = join(root, GENERATED_PATH);
  return !existsSync(path) || readFileSync(path, "utf8") !== want;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    if (isStale(REPO)) {
      console.error(`${GENERATED_PATH} is stale: run \`bun run packs\``);
      process.exit(1);
    }
  } else {
    writeFileSync(
      join(REPO, GENERATED_PATH),
      generated(readFileSync(join(REPO, PACK_PATH), "utf8")),
    );
    console.log(`wrote ${GENERATED_PATH}`);
  }
}
