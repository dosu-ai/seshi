/** What a person typed, told apart from what their agent's harness put in front of it.
 *
 * A session's first "prompt" is often not the person's words: Codex opens with the repository's
 * AGENTS.md and an environment block, Claude Code wraps slash commands and hook output in tags,
 * T3 Code notes which agent sent a message, and harnesses add system reminders. Search results and the team UI show a session by what
 * was asked, so they strip those leading blocks first. Nothing here touches a DOM or Node API:
 * the search index and the page both run it. */

/** A leading `<tag …>…</tag>` block: the wrappers harnesses use (`<environment_context>`,
 * `<system-reminder>`, `<command-name>`, `<INSTRUCTIONS>`, …). */
const TAGGED = /^<([A-Za-z][\w:-]*)(?:\s[^>]*)?>[\s\S]*?<\/\1>\s*/;
/** Codex's AGENTS.md block: a heading line, then the file inside `<INSTRUCTIONS>`. */
const AGENTS_MD =
  /^#\s*AGENTS\.md instructions[^\n]*\n\s*(?:<INSTRUCTIONS>[\s\S]*?<\/INSTRUCTIONS>\s*)?/i;
/** T3 Code's note on a message another agent sent into the thread. */
const T3_NOTE = /^\[T3 Code:[^\]\n]*\]\s*/;
/** Claude Code's note before the output of a command run with `!`. */
const CAVEAT =
  /^Caveat: The messages below were generated by the user while running local commands[^\n]*\n?\s*/;

/** How many leading blocks are stripped at most: a guard, not a limit anyone reaches. */
const MAX_BLOCKS = 20;

export const TITLE_CHARACTERS = 160;

/** `text` without the blocks a harness put before the person's words: `context` is what was
 * taken off (empty when nothing was), `prompt` the rest (empty when the whole text was added
 * by the harness). */
export function splitPrompt(text: string): { context: string; prompt: string } {
  let rest = text.trimStart();
  for (let i = 0; i < MAX_BLOCKS; i++) {
    const block =
      AGENTS_MD.exec(rest) ?? TAGGED.exec(rest) ?? CAVEAT.exec(rest) ?? T3_NOTE.exec(rest);
    if (!block) break;
    rest = rest.slice(block[0].length);
  }
  const prompt = rest.trim();
  const context = text.slice(0, text.length - rest.length).trim();
  return { context, prompt };
}

/** A one-line title for a session from one of its prompts: the person's first line, spaces
 * collapsed, cut near `TITLE_CHARACTERS`. Undefined for a prompt the harness wrote. */
export function promptTitle(text: string): string | undefined {
  const { prompt } = splitPrompt(text);
  const line = prompt
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l !== "");
  if (!line) return undefined;
  // Markdown's emphasis and code marks, and a heading's hashes, say nothing in a title.
  const flat = line
    .replace(/^#{1,6}\s+/, "")
    .replace(/\*\*|__|`/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!flat) return undefined;
  if (flat.length <= TITLE_CHARACTERS) return flat;
  const space = flat.lastIndexOf(" ", TITLE_CHARACTERS);
  return `${flat.slice(0, space > TITLE_CHARACTERS * 0.7 ? space : TITLE_CHARACTERS)}…`;
}
