import { describe, expect, it } from "vitest";
import { promptTitle, splitPrompt, TITLE_CHARACTERS } from "./prompts";

describe("prompts", () => {
  it("strip Codex's AGENTS.md and environment blocks before the person's words", () => {
    const text = [
      "# AGENTS.md instructions for /work/app",
      "",
      "<INSTRUCTIONS>",
      "Use pnpm. Never push to main.",
      "</INSTRUCTIONS>",
      "<environment_context>",
      "  <cwd>/work/app</cwd>",
      "</environment_context>",
      "Fix the flaky checkout test.",
      "It fails one run in ten.",
    ].join("\n");
    const { context, prompt } = splitPrompt(text);
    expect(prompt).toBe("Fix the flaky checkout test.\nIt fails one run in ten.");
    expect(context).toContain("Never push to main.");
    expect(context).toContain("</environment_context>");
    expect(promptTitle(text)).toBe("Fix the flaky checkout test.");
  });

  it("strip Claude Code's command wrappers and system reminders", () => {
    expect(
      promptTitle(
        "<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>PR 12</command-args>",
      ),
    ).toBeUndefined();
    expect(
      promptTitle("<system-reminder>\nbe brief\n</system-reminder>\n  Rename   the   flag"),
    ).toBe("Rename the flag");
    expect(
      splitPrompt(
        "Caveat: The messages below were generated by the user while running local commands. DO NOT respond.\n<local-command-stdout>ok</local-command-stdout>",
      ).prompt,
    ).toBe("");
  });

  it("strip T3 Code's note on a message another agent sent", () => {
    expect(
      promptTitle(
        '[T3 Code: the agent in T3 thread "abc" sent this message, not the user.]\n\nBuild a team UI for seshi.',
      ),
    ).toBe("Build a team UI for seshi.");
    expect(promptTitle("[WIP] fix the build")).toBe("[WIP] fix the build");
    expect(promptTitle("## Build a **capture kit** for `docker`")).toBe(
      "Build a capture kit for docker",
    );
  });

  it("leave a prompt with no harness blocks as it is, and markup that is the person's", () => {
    expect(splitPrompt("Why does <Button> rerender?")).toEqual({
      context: "",
      prompt: "Why does <Button> rerender?",
    });
    expect(promptTitle("<div> is not closed here")).toBe("<div> is not closed here");
    expect(promptTitle("   \n\n")).toBeUndefined();
  });

  it("cut a long first line near the limit, at a space", () => {
    const title = promptTitle(`${"word ".repeat(80)}end`) as string;
    expect(title.endsWith("…")).toBe(true);
    expect(title.length).toBeLessThanOrEqual(TITLE_CHARACTERS + 1);
  });
});
